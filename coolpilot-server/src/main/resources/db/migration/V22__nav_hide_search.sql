-- V22：默认导航不再包含「搜索」项
--
-- 顶栏第一行已经有常驻搜索框（submit 后跳 /search?q=...，搜索页会直接出
-- 文章结果 + AI 语义检索片段）。菜单里的「搜索」是重复入口：点它只会进到一个
-- 空白搜索页，还得再输一次关键词，纯属多一步。
--
-- 处理方式是「设为不可见」而不是 DELETE：
--   1) 站长若想恢复，后台「页面管理 → 导航菜单」把显隐打开即可；
--   2) 保留这一行，菜单的 sort 序列不会因为删行而出现空洞；
--   3) 本迁移只在初始化/本次升级执行一次，之后再改 visible 不会被覆盖。
--
-- 用 path + label 双条件，避免误伤以后新建的其他指向 /search 的菜单项
-- （比如站长自己加一个叫「站内检索」的入口）。
--
-- 注意：V15 的种子数据保持原样不动（改历史脚本会让 checksum 校验失败），
-- 新库会在 V15 插入之后再被这里改成隐藏，最终状态与老库一致。
-- ============================================================

UPDATE `nav_menu`
SET `visible` = b'0'
WHERE `path` = '/search'
  AND `label` = '搜索';
