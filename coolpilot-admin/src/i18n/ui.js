/** 取词函数：中文原文进，当前语言出 */
export function useT() {
	const {locale} = useI18n()
	// 第二个参数做 {name} 形式的简单插值，够后台用；
	// 复杂复数规则不在此列（后台文案没有复数场景）
	return (zh, params) => {
		if (!zh) {
			return zh
		}
		let out = locale.value === 'en' ? (UI_EN[zh] || zh) : zh
		if (params) {
			for (const key of Object.keys(params)) {
				out = out.split(`{${key}}`).join(String(params[key]))
			}
		}
		return out
	}
}
